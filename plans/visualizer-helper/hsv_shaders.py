# Hardstyle visualizer: fill the Olympus Storm template with this song's times and write the Luau that
# applies it, plus the Difference-blend invert layer for the shatter into the biggest drop.
#
#   python hsv_shaders.py OUT_DIR/analysis.json OUT_DIR [--build 12.7]
#
# Writes OUT_DIR/visualizer.glsl, OUT_DIR/rift-invert.glsl and OUT_DIR/shaders.lua (scripts_eval code: set
# VIS at its top; run it AFTER the lyric clips exist so the invert layer lands above them).
# The shatter: --build seconds before the biggest (last) drop the beams/lightning get sucked into the ball
# (starting 2 s earlier), the first glass shard breaks out of the ball's centre on the first hit, then the
# ball and more and more shards invert on every hit, faster and faster, until the drop flash.
import argparse, json, os

ap = argparse.ArgumentParser()
ap.add_argument('analysis'); ap.add_argument('out')
ap.add_argument('--build', type=float, default=12.7)
A = ap.parse_args()
HERE = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(A.analysis))
info, hits = d['info'], d['hits']
drops = info['drops']
if drops:
    big = drops[-1]
    rift0 = max(big - A.build, (drops[-2] + 2.0) if len(drops) > 1 else 2.0)
else:
    big, rift0 = 1e6, 1e6 - 1
kt = [t for t, _ in hits]
h0 = sum(1 for t in kt if t < rift0)
hn = max(sum(1 for t in kt if rift0 <= t < big), 1)
V = {'BIGDROP': big, 'RIFT0': rift0, 'SUCK0': rift0 - 2.0, 'SUCK1': rift0 + 6.0, 'RIFTHIT0': float(h0), 'RIFTHITS': float(hn)}
s = open(os.path.join(HERE, 'olympus-storm.template.glsl'), encoding='utf8').read()
for k, v in V.items(): s = s.replace('{{%s}}' % k, '%.3f' % v)
assert '{{' not in s
open(os.path.join(A.out, 'visualizer.glsl'), 'w', encoding='utf8', newline='\n').write(s)

# the invert layer: the same shader up to the ball size, then only the shard mask (white = invert below)
GEOM_START = s.index('        float prog = clamp((beats - ')
GEOM_END = s.index('        float reach', GEOM_START) if 'float reach' in s[GEOM_START:] else s.index('        vec3 goldL', GEOM_START)
geom = s[GEOM_START:GEOM_END]
MASK = ('\n    // INVERT MASK: white where the colours below get inverted (this clip uses the Difference blend)\n    {\n' + geom +
        '        float m = inv * step(%.3f, u_time) * step(u_time, %.3f);\n        return vec4(vec3(m), m);\n    }\n' % (rift0, big))
anchor = 'float rb = 0.75 * 0.66 * 0.4 * 0.85 * gs;'
j = s.index(anchor) + len(anchor)
m = s[:j] + MASK + s[j:]
# whole ball inverts once it has shattered
m = m.replace('float inv = max(max(first, step(sc.z / 7.0, ballR)),',
              'float inv = max(max(max(first, step(sc.z / 7.0, ballR)), step(0.28, prog) * step(cr, r0 * 1.03)),', 1)
m = m.replace('u_time', '(u_time + %.3f)' % rift0)     # the layer clip starts at RIFT0
m = m.replace('@name Olympus Storm', '@name Olympus Rift Invert', 1)
open(os.path.join(A.out, 'rift-invert.glsl'), 'w', encoding='utf8', newline='\n').write(m)

# shaders.1.lua sets the visualizer shader; shaders.2.lua adds the invert layer; shaders.3+.lua copy the
# visualizer's keys onto it a few params at a time (each plain scripts.run is cut off after 5 s)
for f in os.listdir(A.out):
    if f.startswith('shaders.') and f.endswith('.lua'): os.remove(os.path.join(A.out, f))
def w(i, body): open(os.path.join(A.out, 'shaders.%d.lua' % i), 'w', encoding='utf8').write(body + '\n')
w(1, '-- generated by hsv_shaders.py: the visualizer shader with this song\'s times\nlocal VIS = 0 -- the visualizer clip id\n'
     'local VSRC = [==[' + s + ']==]\nassert(VIS ~= 0, "set VIS")\nlocal r = editor.tool("clip.set_shader", {clip = VIS, src = VSRC}); assert(r.ok, r.log)\nreturn true')
LAYER = '''
assert(VIS ~= 0, "set VIS")
local vis
for _, tr in ipairs(project.get().tracks) do for _, c in ipairs(tr.clips) do if c.id == VIS then vis = c end end end
local add = editor.tool("shapes.add", {at = RIFT0, duration = BIG - RIFT0, kind = "Rect",
  width = vis.shape.w.value, height = vis.shape.h.value, fill = {0, 0, 0, 255}})
local id = add.clip_id or add.id or (add.clip_ids and add.clip_ids[1]); assert(id, "no id")
local r2 = editor.tool("clip.set_shader", {clip = id, src = MSRC}); assert(r2.ok, r2.log)
editor.tool("clip.set", {clip_id = id, fields = {blend = "Difference"}})
return id'''
COPY = '''
assert(VIS ~= 0, "set VIS")
local vis, lay
for _, tr in ipairs(project.get().tracks) do for _, c in ipairs(tr.clips) do
  if c.id == VIS then vis = c end
  local e = c.effects and c.effects[1]
  if e and e.shader and string.find(e.shader, "@name Olympus Rift Invert", 1, true) then lay = c end
end end
assert(lay, "run the invert-layer script first")
local names = {}
for nm in string.gmatch(vis.effects[1].shader, "// @param (%w+)") do names[#names + 1] = nm end
for pi, p in ipairs(vis.effects[1].params) do
  local nm = names[pi]
  if ONLY[nm] then
    local P = "Olympus Rift Invert: " .. nm
    if p.keys then
      local prev, first = nil, true
      for _, k in ipairs(p.keys) do
        if k.t >= RIFT0 and k.t <= BIG + 0.2 then
          if first and prev then editor.tool("clip.keyframe", {clip_id = lay.id, property = P, t = 0, value = prev.v, ease = prev.ease or "Linear"}) end
          first = false
          editor.tool("clip.keyframe", {clip_id = lay.id, property = P, t = k.t - RIFT0, value = k.v, ease = k.ease or "Linear"})
        end
        if k.t < RIFT0 then prev = k end
      end
    else
      editor.tool("clip.keyframe", {clip_id = lay.id, property = P, t = 0, value = p.value, ease = "Hold"})
    end
  end
end
return lay.id'''
if drops:
    w(2, '-- generated by hsv_shaders.py: the shatter invert layer (Difference blend) on the top video track\n'
         'local VIS = 0 -- the visualizer clip id\nlocal RIFT0, BIG = %.3f, %.3f\nlocal MSRC = [==[' % (rift0, big) + m + ']==]' + LAYER)
    names = [ln.split()[2] for ln in s.splitlines() if ln.startswith('// @param ')]
    groups = [['level'], ['band1'], ['band4'], [n for n in names if n not in ('level', 'band1', 'band4', 'wave', 'lyric')]]
    for gi, grp in enumerate(groups, 3):
        w(gi, '-- generated by hsv_shaders.py: copy visualizer keys onto the invert layer: ' + ', '.join(grp) + '\n'
              'local VIS = 0 -- the visualizer clip id\nlocal RIFT0, BIG = %.3f, %.3f\nlocal ONLY = {%s}\n'
              % (rift0, big, ', '.join('%s = true' % g for g in grp)) + COPY)

# the background grade: black before the first drop, a bright golden-hour look from it, a gold-only duotone
# (low saturation + gold tint + contrast) through the biggest drop until the song calms down
lut = os.path.join(HERE, 'golden-hour.cube').replace('\\', '/')
d1 = drops[0] if drops else 0.0
calm = info.get('calm') or info['duration']
B = ['-- generated by hsv_shaders.py: background grade (one undo step)', 'local BG = 0 -- the background clip id',
     'local LUT = "%s"' % lut, 'local D1, BIG, CALM, TWO, RIFT0 = %.3f, %.3f, %.3f, %s, %.3f' % (d1, big if drops else 0, calm, 'true' if len(drops) > 1 else 'false', rift0),
     r'''assert(BG ~= 0, "set BG")
local function key(p, t, v, e) editor.tool("clip.keyframe", {clip_id = BG, property = p, t = t, value = v, ease = e or "Linear"}) end
-- the LUT: clip.add_lut is not available to scripts, add it first over MCP: clip.add_lut {clip_id, path = LUT}
editor.tool("clip.add_effect", {clip_id = BG, kind = "Levels"})
editor.tool("clip.add_effect", {clip_id = BG, kind = "Color Correction"})
editor.tool("clip.add_effect", {clip_id = BG, kind = "Color Tint", params = {Amount = 0, Red = 255, Green = 176, Blue = 40}})
-- black until the first drop, then on at full
key("opacity", 0, 0, "Hold")
if BIG > D1 + 1 or BIG == 0 then key("opacity", D1, 1, "Hold")
else -- one drop: the scenery creeps in (dark) under the shatter so the inverted shards show scenery, not white
  key("opacity", RIFT0, 0, "EaseIn"); key("opacity", BIG - 0.02, 0.75, "Hold"); key("opacity", BIG, 1, "Hold") end
key("Color Correction: Brightness", 0, -0.45); key("Color Correction: Brightness", D1 - 0.02, -0.12, "Linear"); key("Color Correction: Brightness", D1, 0.06)
key("Levels: In white", 0, 0.44, "Hold")
if TWO then
  key("Levels: In white", BIG, 0.85, "Hold"); key("Levels: In white", CALM, 0.44, "Hold")
  key("Color Correction: Saturation", 0, 1, "Hold"); key("Color Correction: Saturation", BIG, 0.1, "Hold"); key("Color Correction: Saturation", CALM, 1, "Hold")
  key("Color Correction: Contrast", 0, 1, "Hold"); key("Color Correction: Contrast", BIG, 1.2, "Hold"); key("Color Correction: Contrast", CALM, 1, "Hold")
  key("Color Tint: Amount", 0, 0, "Hold"); key("Color Tint: Amount", BIG, 0.72, "Hold"); key("Color Tint: Amount", CALM, 0, "Hold")
end
return true''']
open(os.path.join(A.out, 'background.lua'), 'w', encoding='utf8').write('\n'.join(B) + '\n')
print(json.dumps(V))
